from typing import TypedDict


class QueueState(TypedDict):
    patient_name: str
    doctor_name: str
    appointment_time: str
    symptoms: str
    booking_status: str

    risk_score: int
    token_number: int
    priority: str


def queue_agent(state: QueueState) -> QueueState:

    risk = state["risk_score"]

    # -----------------------------------------
    # Decide priority from risk score
    # -----------------------------------------

    if risk >= 80:

        state["priority"] = "High"

    elif risk >= 50:

        state["priority"] = "Medium"

    else:

        state["priority"] = "Low"

    # -----------------------------------------
    # IMPORTANT
    # -----------------------------------------
    # Do NOT change token_number here.
    # Token number is already generated by Django
    # from the database.

    print("\n===== Queue Agent =====")
    print(f"Risk Score : {state['risk_score']}")
    print(f"Priority   : {state['priority']}")
    print(f"Token No   : {state['token_number']}")

    return state